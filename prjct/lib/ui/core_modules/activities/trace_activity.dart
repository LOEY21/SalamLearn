  bool get _counting =>
      _count.isAnimating && _count.value * _kCountTotal < _kCountSecs;

  /// Ticks each number of the countdown; at "Go!" play begins.
  void _onCount() {
    final secs = _count.value * _kCountTotal;
    final n = secs < _kCountSecs ? 3 - secs.floor() : 0;
    if (n == _countShown) return;
    _countShown = n;
    _click();
    if (n != 0) return;
    setState(() {});
    _clock.forward(from: 0);
    _watch
      ..reset()
      ..start();
    _say();
  }

  /// The ending's Replay: same letters from the top.
  void _replay() {
    setState(() {
      _idx = 0;
      _scores.clear();
      _failedChecks = 0;
      _accuracy = 0;
      _checked = false;
      _passed = false;
      _clearCounter++;
    });
    _go();
  }

  double get _average =>
      _scores.isEmpty ? 0 : _scores.reduce((a, b) => a + b) / _scores.length;

