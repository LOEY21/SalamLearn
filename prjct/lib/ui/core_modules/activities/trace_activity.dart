  final double v;

  @override
  void paint(Canvas canvas, Size size) {
    final c = size.center(Offset.zero);
    final out = Curves.easeOutCubic.transform(v);
    final fade = 1 - v;

    final ray = Paint()
      ..color = const Color(0xFFFFD45C).withValues(alpha: .45 * fade);
    for (var i = 0; i < 14; i++) {
      final a = i * 2 * math.pi / 14 + v * .6;
      final len = 90 + 260 * out;
      final dir = Offset(math.cos(a), math.sin(a));
      final side = Offset(-dir.dy, dir.dx) * 14;
      canvas.drawPath(
        Path()
          ..moveTo(c.dx + dir.dx * 60, c.dy + dir.dy * 60)
          ..lineTo(c.dx + dir.dx * len + side.dx, c.dy + dir.dy * len + side.dy)
          ..lineTo(c.dx + dir.dx * len - side.dx, c.dy + dir.dy * len - side.dy)
          ..close(),
        ray,
      );
    }

    canvas.drawCircle(
      c,
      70 + 300 * out,
      Paint()
        ..style = PaintingStyle.stroke
        ..strokeWidth = 12 * fade + 1
        ..color = const Color(0xFFFFF3D6).withValues(alpha: .8 * fade),
    );

    for (var i = 0; i < 16; i++) {
      final a = i * 2 * math.pi / 16 + (i.isEven ? .2 : -.1);
      final d = (i.isEven ? 170 : 240) * out + 50;
      final p = c + Offset(math.cos(a), math.sin(a)) * d;
      final r = 16 * fade + 4;
      canvas.drawPath(
        Path()
          ..moveTo(p.dx, p.dy - r)
          ..quadraticBezierTo(p.dx, p.dy, p.dx + r, p.dy)
          ..quadraticBezierTo(p.dx, p.dy, p.dx, p.dy + r)
          ..quadraticBezierTo(p.dx, p.dy, p.dx - r, p.dy)
          ..quadraticBezierTo(p.dx, p.dy, p.dx, p.dy - r),
        Paint()
          ..color = (i % 3 == 0 ? Colors.white : const Color(0xFFF4B400))
              .withValues(alpha: fade),
      );
    }
  }

  @override
  bool shouldRepaint(_BurstPainter old) => old.v != v;
}

/// The ending's confetti: paper bits drifting down on a loop, each
/// fluttering (its width flipping as it tumbles) and swaying as it falls.
class _ConfettiPainter extends CustomPainter {
  _ConfettiPainter(this.t);

  final double t;

  static const _colors = [
    Color(0xFFF4B400),
    Color(0xFF2FAE5B),
    Color(0xFFFF7A59),
    Color(0xFF3BB6E8),
    Color(0xFFFFFFFF),
  ];

  @override
  void paint(Canvas canvas, Size size) {
    double h(int i, int k) {
      final v = math.sin(i * 12.9898 + k * 78.233) * 43758.5453;
      return v - v.floorToDouble();
    }

    for (var i = 0; i < 70; i++) {
      final fall = 120 + 160 * h(i, 1);
      final y = (h(i, 2) * size.height + t * fall) % (size.height + 60) - 30;
      final x = h(i, 3) * size.width + 30 * math.sin(t * (1 + h(i, 4)) + i);
      final flip = math.cos(t * (3 + 4 * h(i, 5)) + i);
      canvas.save();
      canvas.translate(x, y);
      canvas.rotate(t * (1 + 2 * h(i, 6)) + i);
      canvas.drawRect(
        Rect.fromCenter(
          center: Offset.zero,
          width: 22 * flip.abs() + 2,
          height: 12,
        ),
        Paint()..color = _colors[i % _colors.length],
      );
      canvas.restore();
    }
  }

  @override
  bool shouldRepaint(_ConfettiPainter old) => old.t != t;
}

/// The wind over the courtyard, 0.24-1: a slow swell with a quicker gust on
/// top, so every plant leans with the same weather.
double _gust(double t) =>
    0.62 + 0.25 * math.sin(0.23 * t) + 0.13 * math.sin(0.61 * t + 1.7);

/// The live backdrop, drawn by `shaders/sand_tracer_bg.frag` from [layers]
/// (clean, palms, field, aux, clouds) at [t] seconds.
class _LiveBgPainter extends CustomPainter {
  _LiveBgPainter(this.shader, this.layers, this.t);

  final ui.FragmentShader shader;
  final List<ui.Image> layers;
  final double t;

  @override
  void paint(Canvas canvas, Size size) {
    shader
      ..setFloat(0, size.width)
      ..setFloat(1, size.height)
      ..setFloat(2, t)
      ..setFloat(3, _gust(t));
    for (var i = 0; i < layers.length; i++) {
      shader.setImageSampler(i, layers[i]);
    }
    canvas.drawRect(Offset.zero & size, Paint()..shader = shader);
  }

  @override
  bool shouldRepaint(_LiveBgPainter old) => old.t != t;
}

/// Yellow shine dashes fanning out from the Play button's top corners;
/// [glow] 0..1 pulses their opacity.
class _SparkPainter extends CustomPainter {
  _SparkPainter(this.glow);

  final double glow;

  @override
  void paint(Canvas canvas, Size size) {
    final paint = Paint()
      ..color = const Color(0xFFFFD84A).withValues(alpha: .45 + .55 * glow)
      ..strokeWidth = 9
      ..strokeCap = StrokeCap.round;
    for (final side in [-1.0, 1.0]) {
      final c = Offset(
        size.width / 2 + side * size.width * .40,
        size.height * .30,
      );
      for (final a in [-.35, .15, .65]) {
        final dir = Offset(side * math.cos(a), -math.sin(a));
        canvas.drawLine(c + dir * 40, c + dir * 68, paint);
      }
    }
  }

  @override
  bool shouldRepaint(_SparkPainter old) => old.glow != glow;
}

/// Image button that swaps to its `_down` art while held; [child] (icon or
/// label) sits centred on the raised face and dips a touch with the press.
class _PressImg extends StatefulWidget {
  const _PressImg({
    super.key,
    required this.asset,
    required this.onTap,
    required this.child,
    this.lift = 0,
  });

  final String asset;
  final VoidCallback onTap;
  final Widget child;

  /// How far the art's raised face sits above the image's centre (the lip
  /// and shadow are below it), so [child] centres on the face.
  final double lift;

  @override
  State<_PressImg> createState() => _PressImgState();
}

class _PressImgState extends State<_PressImg> {
  bool _down = false;

  void _set(bool v) {
    if (_down != v) setState(() => _down = v);
  }

  @override
  Widget build(BuildContext context) => Semantics(
    button: true,
    child: GestureDetector(
      behavior: HitTestBehavior.opaque,
      onTapDown: (_) => _set(true),
      onTapUp: (_) => _set(false),
      onTapCancel: () => _set(false),
      onTap: widget.onTap,
      child: Stack(
        fit: StackFit.expand,
        children: [
          Image.asset(
            '${widget.asset}${_down ? '_down' : ''}.png',
            scale: 2,
            fit: BoxFit.fill,
          ),
          Transform.translate(
            offset: Offset(0, -widget.lift + (_down ? 1 : 0)),
            child: widget.child,
          ),
        ],
      ),
    ),
  );
}
