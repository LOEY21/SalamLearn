  static LetterTrace? _traceOf(FlashCard card) {
    final parts = card.arabic.split('\n');
    var key = (parts.length > 1 ? parts.last : card.arabic).trim();
    if (key == 'أ' || key == 'إ' || key == 'آ') key = 'ا';
    if (key == 'ة') key = 'ت';
    if (key == 'ى') key = 'ي';
    return letterTraces[key];
  }

