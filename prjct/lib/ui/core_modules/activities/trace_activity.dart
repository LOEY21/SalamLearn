  /// The ending's Replay: same letters from the top.
  void _replay() {
    setState(() {
      _idx = 0;
      _scores.clear();
      _failedChecks = 0;
      _accuracy = 0;
      _checked = false;
      _passed = false;
      _clearCounter++;
    });
    _go();
  }

  double get _average =>
      _scores.isEmpty ? 0 : _scores.reduce((a, b) => a + b) / _scores.length;

