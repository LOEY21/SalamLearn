  /// The tray's sand, traced off `game_tray.png` and put in the tracing
  /// canvas's own 638x499 stage units (the canvas covers the sand's bounds).
  /// It's a trapezoid, narrower at the top, so a plain rectangle would let
  /// the letter run over the frame.
  static const _kSandW = 638.0;
  static const _kSandH = 499.0;
  static const _kSandPoly = <double>[
    545, 26, 563, 70, 637, 413, 638, 439, 599, 488, 571, 496, 511, 499, //
    97, 499, 40, 487, 27, 476, 0, 434, 1, 409, 60, 138, 87, 36, 100, 15,
    113, 5, 131, 0, 486, 0, 521, 5,
  ];

  /// The sand's outline at the canvas's actual [size].
  static Path _sand(Size size) {
    final sx = size.width / _kSandW, sy = size.height / _kSandH;
    return Path()..addPolygon([
      for (var i = 0; i < _kSandPoly.length; i += 2)
        Offset(_kSandPoly[i] * sx, _kSandPoly[i + 1] * sy),
    ], true);
  }

  /// Last [_fit], reused across frames (it's asked for on every paint).
  (LetterTrace, Size, Offset Function(double, double))? _fitCache;

  /// Maps the letter's unit space onto [size]: centred on the sand and as
  /// large as it can be with its whole box, plus a margin for the outline's
  /// thickening and the number badges, still inside the sand.
  Offset Function(double x, double y) _fit(LetterTrace t, Size size) {
    final cached = _fitCache;
    if (cached != null && cached.$1 == t && cached.$2 == size) return cached.$3;
    var minX = double.infinity, maxX = -double.infinity;
    var minY = double.infinity, maxY = -double.infinity;
    for (final c in t.outline) {
      for (var i = 0; i < c.length; i += 2) {
        minX = math.min(minX, c[i]);
        maxX = math.max(maxX, c[i]);
        minY = math.min(minY, c[i + 1]);
        maxY = math.max(maxY, c[i + 1]);
      }
    }
    final w = maxX - minX, h = maxY - minY;
    final centre = Offset(size.width / 2, size.height * .52);
    final sand = _sand(size);
    final margin = 14 + size.shortestSide * .04;
    // The sand is convex, so the box fits if its four corners do.
    bool fits(double scale) {
      final hw = w * scale / 2 + margin, hh = h * scale / 2 + margin;
      return [
        centre + Offset(-hw, -hh),
        centre + Offset(hw, -hh),
        centre + Offset(-hw, hh),
        centre + Offset(hw, hh),
      ].every(sand.contains);
    }

    var lo = 0.0, hi = math.min(size.width / w, size.height / h);
    for (var i = 0; i < 24; i++) {
      final mid = (lo + hi) / 2;
      if (fits(mid)) {
        lo = mid;
      } else {
        hi = mid;
      }
    }
    final left = centre.dx - w * lo / 2 - minX * lo;
    final top = centre.dy - h * lo / 2 - minY * lo;
    Offset at(double x, double y) => Offset(left + x * lo, top + y * lo);
    _fitCache = (t, size, at);
    return at;
  }

  static List<Offset> _points(
    List<double> flat,
    Offset Function(double, double) at,
  ) => [for (var i = 0; i < flat.length; i += 2) at(flat[i], flat[i + 1])];

  List<List<Offset>> _guideStrokes(Size size) => _guideStrokesFor(_trace, size);

  List<List<Offset>> _guideStrokesFor(LetterTrace? t, Size size) {
    if (t == null) return [];
    final at = _fit(t, size);
    return [for (final s in t.strokes) _points(s, at)];
  }

  /// The letter's own outline at the same fit as [_guideStrokes].
  Path _glyphFor(LetterTrace? t, Size size) {
    final path = Path();
    if (t == null) return path;
    final at = _fit(t, size);
    for (final c in t.outline) {
      path.addPolygon(_points(c, at), true);
    }
    return path;
  }

  /// Accuracy per stroke blends two measures so both failure modes get
  /// caught: recall (how much of the guide the learner actually traced)
  /// and precision (how closely the learner's own marks stuck to the
  /// guide). Recall alone let a broad scribble across the whole card
  /// "cover" every guide point and score as a near-perfect trace, since
  /// nothing penalized ink that strayed off the letter. The average
  /// across strokes (including dots) keeps every stroke weighted
  /// equally so body strokes don't dominate the check.
  double _computeAccuracy(List<List<Offset>> userStrokes, Size canvasSize) {
    if (userStrokes.isEmpty) return 0.0;
    final guideStrokes = _guideStrokes(canvasSize);
    if (guideStrokes.isEmpty) return 0.0;
    final tolerance = _boxSizeFor(canvasSize) * 0.12;

    var totalScore = 0.0;
    for (var i = 0; i < guideStrokes.length; i++) {
      final guide = guideStrokes[i];
      if (guide.isEmpty) continue;
      if (i >= userStrokes.length) continue;
      final user = userStrokes[i];
      if (user.isEmpty) continue;

      var covered = 0;
      for (final gp in guide) {
        for (final up in user) {
          if ((up - gp).distance <= tolerance) {
            covered++;
            break;
          }
        }
      }
      final recall = covered / guide.length;

      var onPath = 0;
      for (final up in user) {
        for (final gp in guide) {
          if ((up - gp).distance <= tolerance) {
            onPath++;
            break;
          }
        }
      }
      final precision = onPath / user.length;

      totalScore += recall * 0.6 + precision * 0.4;
    }

    return totalScore / guideStrokes.length;
  }

  void _handleStroke(List<List<Offset>> userStrokes, Size canvasSize) {
    final acc = _computeAccuracy(userStrokes, canvasSize);
    setState(() => _accuracy = acc);
    if (acc >= _autoPassThreshold && !_passed) {
      setState(() {
        _checked = true;
        _passed = true;
      });
      _clock.stop();
      _showVerdict(true);
    }
  }

  void _showVerdict(bool pass) {
    _verdictPass = pass;
    _verdict.forward(from: 0);
  }

  void _handleCheck() {
    if (_accuracy < 0.1) {
      _wobble.forward(from: 0);
      return;
    }
    final passed = _accuracy >= _passThreshold;
    setState(() {
      _checked = true;
      _passed = passed;
    });
    _click();
    _showVerdict(passed);
    if (passed) _clock.stop();
    if (!passed) {
      _failedChecks++;
      _wobble.forward(from: 0);
      Future.delayed(const Duration(milliseconds: 700), () {
        if (mounted) setState(() => _checked = false);
      });
    }
  }

  void _next() {
    _scores.add(_accuracy);
    if (_idx + 1 >= widget.cards.length) {
      _clock.stop();
      _watch.stop();
      _click();
      setState(() => _screen = _Screen.done);
      _enter.forward(from: 0);
    } else {
      setState(() {
        _idx += 1;
        _accuracy = 0.0;
        _checked = false;
        _passed = false;
      });
      _verdict.value = 0;
      _wipe.forward(from: 0);
      _clock.forward(from: 0);
      _say();
    }
  }

  int _clearCounter = 0;

  void _clear() {
    setState(() {
      _click();
      _accuracy = 0.0;
      _checked = false;
      _passed = false;
      _clearCounter++;
    });
    _verdict.value = 0;
    _wipe.forward(from: 0);
    // A pass froze the timer; clearing to try again sets it running again.
    if (!_clock.isAnimating && _clock.value < 1) _clock.forward();
  }

  void _click() {
    if (_sound) SystemSound.play(SystemSoundType.click);
  }

  void _say() {
    if (!_sound) return;
    final asset = _card.audioAsset;
    if (asset != null && _audio != null) {
      unawaited(_audio!.playLetter(asset));
    } else {
      _click();
    }
  }

  void _toggleMusic() {
    setState(() => _music = !_music);
    if (_audio != null) unawaited(_audio!.setMusicEnabled(_music));
  }

  void _toggleSound() {
    setState(() => _sound = !_sound);
    if (!_sound && _audio != null) unawaited(_audio!.stopLetter());
  }

