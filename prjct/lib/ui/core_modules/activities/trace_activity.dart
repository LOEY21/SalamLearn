  @override
  Widget build(BuildContext context) {
    switch (_screen) {
      case _Screen.start:
        return _buildStart();
      case _Screen.howTo:
        return _stage(_buildHowTo());
      case _Screen.done:
        return _stage(_buildDone());
      case _Screen.play:
        break;
    }
    final topInset = MediaQuery.of(context).padding.top;
    return LayoutBuilder(
      builder: (context, box) {
        final h = box.maxHeight - topInset;
        final s = math.min(box.maxWidth / _kW, h / _kH);
        final ox = (box.maxWidth - _kW * s) / 2;
        final oy = topInset + (h - _kH * s) / 2;
        // Screen-space twin of [_at] for layers kept outside the stage.
        Widget place(double l, double t, double w, double hh, Widget c) =>
            Positioned(
              left: ox + l * s,
              top: oy + t * s,
              width: w * s,
              height: hh * s,
              child: c,
            );
        return Stack(
          fit: StackFit.expand,
          children: [
            _liveBg(),
            Padding(
              padding: EdgeInsets.only(top: topInset),
              child: FittedBox(
                child: SizedBox(width: _kW, height: _kH, child: _buildHud()),
              ),
            ),
            // Traced in screen pixels rather than inside the scaled stage,
            // so ink width and tolerances match the device.
            // Over the sand only, and clipped to it: nothing drawn while
            // tracing can land on the frame or beyond.
            place(
              109,
              944,
              _kSandW,
              _kSandH,
              ClipPath(clipper: _SandClip(), child: _buildCanvas()),
            ),
          ],
        );
      },
    );
  }

