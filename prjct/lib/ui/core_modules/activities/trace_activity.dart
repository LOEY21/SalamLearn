                            )
                          : Stack(
                              fit: StackFit.expand,
                              children: [
                                DecoratedBox(decoration: _panel(150)),
                                Padding(
                                  padding: const EdgeInsets.all(18),
                                  child: CircularProgressIndicator(
                                    value: 1 - local,
