/// FR-4.1's Tactile Recognition Engine — tracks the learner's continuous
/// drag (X/Y samples) and validates it against a predefined right-to-left
/// vector path drawn in the actual shape of the Arabic letter on the card.
///
/// Each letter's shape and stroke paths come from the bundled ScheherazadeNew
/// Bold font's own isolated-form glyph (`lib/data/letter_trace_data.dart`, generated by
/// `dumps/tracing_layers/gen_letter_paths.py`): the outline is the tracing
/// mask, and the paths run along the glyph's centre in writing order.

class TraceActivity extends StatefulWidget {
  const TraceActivity({
    super.key,
    required this.cards,
    required this.xp,
    required this.color,
    required this.onComplete,
    required this.onBack,
    this.audioEnabled = true,
  });

  final List<FlashCard> cards;
  final int xp;
  final Color color;
  final void Function(int xp, double accuracyPct, int errors) onComplete;

  /// `LessonPlayerScreen` skips its own top bar for trace (see its
  /// `_activity.type` switch) since this scene's back control is baked into
  /// its own scenery instead — the yellow circular arrow drawn here, not a
  /// bar-mounted one.
  final VoidCallback onBack;
  final bool audioEnabled;

  @override
  State<TraceActivity> createState() => _TraceActivityState();
}

