import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:firebase_core/firebase_core.dart'; // New
import 'package:connectivity_plus/connectivity_plus.dart';

import 'data/local/hive_boxes.dart';
import 'data/remote/firebase_role_app.dart';
import 'firebase_options.dart'; // New (Generated by the command above)
import 'logic/router/app_router.dart';
import 'logic/connectivity/internet_access.dart';
import 'ui/theme/app_colors.dart';
import 'ui/theme/app_theme.dart';
import 'ui/widgets/internet_status_shell.dart';

void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Initialize Firebase before the app boots up
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  // Teacher's own sign-in, so parent and teacher stay signed in together.
  await FirebaseRoleApp.initTeacherApp(DefaultFirebaseOptions.currentPlatform);

  // Local-first persistence (Hive) — must be ready before any provider
  // reads/writes a box.
  await HiveService.init();

  await SystemChrome.setPreferredOrientations([
    DeviceOrientation.portraitUp,
    DeviceOrientation.portraitDown,
  ]);

  // Parent/Teacher (and every other admin/onboarding screen) keep the
  // normal system status + navigation bars. Only the Learner Hub goes
  // fullscreen immersive — see `HubShell`'s own SystemChrome calls, which
  // switch into immersiveSticky on entry and restore this default on exit.
  await SystemChrome.setEnabledSystemUIMode(SystemUiMode.edgeToEdge);

  runApp(const ProviderScope(child: SalamLearnApp()));
}

class SalamLearnApp extends ConsumerWidget {
  const SalamLearnApp({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    return MaterialApp.router(
      title: 'SalamLearn',
      debugShowCheckedModeBanner: false,
      theme: AppTheme.light(),
      routerConfig: ref.watch(routerProvider),
      // Edge-to-edge draws under the Android 3-button nav bar, so inset
      // every screen above it. Immersive screens report zero padding.
      builder: (context, child) => ColoredBox(
        color: AppColors.cream,
        child: SafeArea(
          top: false,
          left: false,
          right: false,
          child: MediaQuery.withClampedTextScaling(
            maxScaleFactor: 1.3,
            child: InternetStatusShell(
              checkInternet: ref.read(internetAccessProvider),
              connectivityChanges: Connectivity().onConnectivityChanged,
              child: child ?? const SizedBox.shrink(),
            ),
          ),
        ),
      ),
    );
  }
}
