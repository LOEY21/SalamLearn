void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Initialize Firebase before the app boots up
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  // Teacher's own sign-in, so parent and teacher stay signed in together.
  await FirebaseRoleApp.initTeacherApp(DefaultFirebaseOptions.currentPlatform);

  // Local-first persistence (Hive) — must be ready before any provider
  // reads/writes a box.
  await HiveService.init();
  await LocalizedAssetBundle.init();
  await LocalNotifications.init();

  // Each game runs music and narration on separate players. With Android's
  // default focus, every voice line takes audio focus from the music player
  // and Android stops the music for good — so every player mixes instead.
  try {
    await AudioPlayer.global.setAudioContext(
      AudioContextConfig(focus: AudioContextConfigFocus.mixWithOthers).build(),
    );
  } catch (_) {
    // No audio output: the games still run, silently.
  }

  await SystemChrome.setPreferredOrientations([
    DeviceOrientation.portraitUp,
    DeviceOrientation.portraitDown,
  ]);

  // Parent/Teacher (and every other admin/onboarding screen) keep the
  // normal system status + navigation bars. Only the Learner Hub goes
  // fullscreen immersive — see `HubShell`'s own SystemChrome calls, which
  // switch into immersiveSticky on entry and restore this default on exit.
  await SystemChrome.setEnabledSystemUIMode(SystemUiMode.edgeToEdge);

  runApp(const ProviderScope(child: SalamLearnApp()));
  // Screen size is only reliable once the first frame is laid out — then
  // unlock rotation if this turns out to be a tablet.
  WidgetsBinding.instance.addPostFrameCallback((_) => restoreAppOrientations());
}

class SalamLearnApp extends ConsumerWidget {
  const SalamLearnApp({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final router = ref.watch(routerProvider);
    return DefaultAssetBundle(
      bundle: _bundle,
      child: MaterialApp.router(
        title: 'SalamLearn',
        debugShowCheckedModeBanner: false,
        theme: AppTheme.light(),
        routerConfig: router,
        // Edge-to-edge draws under the Android 3-button nav bar, so inset
        // every screen above it. Immersive screens report zero padding.
        builder: (context, child) => ListenableBuilder(
          listenable: router.routerDelegate,
          builder: (context, _) => ColoredBox(
            color: AppColors.cream,
            child: SafeArea(
              top: false,
              left: false,
              right: false,
              // The onboarding and role screens' white canvas and blobs run
              // to the screen's edges; they inset their own content.
              bottom: !_fullBleed.contains(
                router.routerDelegate.currentConfiguration.uri.path,
              ),
              child: MediaQuery.withClampedTextScaling(
                maxScaleFactor: 1.3,
                child: InternetStatusShell(
                  checkInternet: ref.read(internetAccessProvider),
                  connectivityChanges: Connectivity().onConnectivityChanged,
                  child: child ?? const SizedBox.shrink(),
                ),
              ),
            ),
          ),
        ),
      ),
    );
  }
}

const _fullBleed = {'/get-started', '/language', '/consent', '/roles', '/auth'};

/// Swaps in the games' Filipino button art while the app is in Filipino.
final _bundle = LocalizedAssetBundle();
